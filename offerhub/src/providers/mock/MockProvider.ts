import type { NormalizedOffer } from "@/types/offer";
import { OfferProvider, type RawOffer } from "@/providers/base/OfferProvider";

/**
 * Deterministic sample feed so the full pipeline (sync → normalize →
 * rank → browse → click) works on day one, before any network keys
 * exist. Disable in production with ENABLE_MOCK_PROVIDER=false.
 */
export class MockProvider extends OfferProvider {
  readonly slug = "mock";
  readonly name = "SampleWall";

  isConfigured(): boolean {
    return process.env.ENABLE_MOCK_PROVIDER !== "false";
  }

  async fetchOffers(): Promise<RawOffer[]> {
    return SAMPLE_OFFERS;
  }

  protected normalize(raw: RawOffer): NormalizedOffer | null {
    const externalId = this.asString(raw.id);
    const title = this.asString(raw.title);
    const url = this.asString(raw.url);
    if (!externalId || !title || !url) return null;

    return {
      externalId,
      title,
      description: this.asString(raw.description),
      requirements: this.asString(raw.requirements),
      imageUrl: this.asString(raw.image),
      bannerUrl: this.asString(raw.banner),
      url,
      rewardAmount: this.asNumber(raw.reward) ?? 0,
      rewardCurrency: "USD",
      payout: this.asNumber(raw.payout),
      device: this.mapDevice(raw.device),
      categorySlug: this.mapCategory(raw.category),
      countries: this.mapCountries(raw.countries),
      estimatedMinutes: this.asNumber(raw.minutes),
      approvalDays: this.asNumber(raw.approval),
      raw,
    };
  }
}

